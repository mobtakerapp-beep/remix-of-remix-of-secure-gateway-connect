export type Dict = Record<keyof typeof dict.ar, string>;

const Ctx = createContext<{ lang: UiLang; setLang: (l: UiLang) => void; t: Dict }>({
  lang: "ar",
  setLang: () => {},
  t: dict.ar,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<UiLang>("ar");

  useEffect(() => {
    const saved = localStorage.getItem("ui-lang");
    if (saved === "en" || saved === "ar") setLang(saved);
  }, []);

  useEffect(() => {
    localStorage.setItem("ui-lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  return <Ctx.Provider value={{ lang, setLang, t: dict[lang] }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
